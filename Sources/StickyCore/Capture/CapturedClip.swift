import Foundation

/// A raw, in-memory copy of a pasteboard (or a drop) before anything is written to disk.
public struct CapturedClip: Sendable {
    public struct Entry: Sendable, Equatable {
        public var type: String
        public var data: Data
        public init(type: String, data: Data) {
            self.type = type
            self.data = data
        }
    }

    public struct Element: Sendable, Equatable {
        public var entries: [Entry]
        /// The file this pasteboard item stands for, if any.
        public var fileURL: URL?
        public init(entries: [Entry], fileURL: URL? = nil) {
            self.entries = entries
            self.fileURL = fileURL
        }

        public func data(_ type: String) -> Data? { entries.first { $0.type == type }?.data }
        public var types: [String] { entries.map(\.type) }
    }

    public var elements: [Element]
    /// Files received through file promises (Photos, Mail, Safari…), already in our staging folder.
    public var stagedFiles: [URL]
    public var concealed: Bool
    public var sourceBundleID: String?
    /// Types we left out (too big or pure noise); kept for diagnostics.
    public var skipped: [String]

    public init(elements: [Element], stagedFiles: [URL] = [], concealed: Bool = false,
                sourceBundleID: String? = nil, skipped: [String] = []) {
        self.elements = elements
        self.stagedFiles = stagedFiles
        self.concealed = concealed
        self.sourceBundleID = sourceBundleID
        self.skipped = skipped
    }

    public var fileURLs: [URL] { elements.compactMap(\.fileURL) }
    public var isEmpty: Bool { elements.allSatisfy { $0.entries.isEmpty && $0.fileURL == nil } && stagedFiles.isEmpty }

    /// First element that has data for any of `types`.
    public func firstData(_ types: [String]) -> (type: String, data: Data)? {
        for element in elements {
            for type in types {
                if let data = element.data(type) { return (type, data) }
            }
        }
        return nil
    }

    public var plainText: String? {
        if let data = firstData([UTI.utf8Text])?.data, let s = String(data: data, encoding: .utf8) { return s }
        if let data = firstData([UTI.utf16Text])?.data, let s = String(data: data, encoding: .utf16) { return s }
        if let data = firstData([UTI.legacyString])?.data, let s = String(data: data, encoding: .utf8) { return s }
        return nil
    }
}

/// Pasteboard type identifiers we care about by name.
public enum UTI {
    public static let utf8Text = "public.utf8-plain-text"
    public static let utf16Text = "public.utf16-external-plain-text"
    public static let legacyString = "NSStringPboardType"
    public static let rtf = "public.rtf"
    public static let rtfd = "com.apple.flat-rtfd"
    public static let html = "public.html"
    public static let url = "public.url"
    public static let urlName = "public.url-name"
    public static let fileURL = "public.file-url"
    public static let png = "public.png"
    public static let tiff = "public.tiff"
    public static let jpeg = "public.jpeg"
    public static let heic = "public.heic"
    public static let gif = "com.compuserve.gif"
    public static let webp = "org.webmproject.webp"
    public static let pdf = "com.adobe.pdf"
    public static let color = "com.apple.cocoa.pasteboard.color"
    // nspasteboard.org conventions
    public static let concealed = "org.nspasteboard.ConcealedType"
    public static let transient = "org.nspasteboard.TransientType"
    public static let autoGenerated = "org.nspasteboard.AutoGeneratedType"
    public static let source = "org.nspasteboard.source"

    public static let images = [png, tiff, jpeg, heic, gif, webp, "public.image", "Apple PNG pasteboard type", "NeXT TIFF v4.0 pasteboard type"]
    public static let richText = [rtf, rtfd, html, "com.apple.webarchive", "NeXT Rich Text Format v1.0 pasteboard type"]
}
