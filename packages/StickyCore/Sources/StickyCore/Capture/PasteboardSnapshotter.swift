import Foundation

/// The limits for reading a pasteboard. The capture implementation itself lives in the
/// macOS-only extension below; the type is portable so `CaptureService` can share its settings.
public enum PasteboardSnapshotter {
    public struct Limits: Sendable {
        public var perType: Int
        public var total: Int
        public init(perType: Int = 64 * 1024 * 1024, total: Int = 256 * 1024 * 1024) {
            self.perType = perType
            self.total = total
        }
    }
}

#if os(macOS)
import AppKit

extension PasteboardSnapshotter {
    /// Bookkeeping types that describe *how* data is delivered rather than the data itself.
    static let noise: Set<String> = [
        "com.apple.pasteboard.promised-file-url",
        "com.apple.pasteboard.promised-file-content-type",
        "com.apple.pasteboard.promised-suggested-file-name",
        "com.apple.NSFilePromiseItemMetaData",
        "NSPromiseContentsPboardType",
        "Apple files promise pasteboard type",
        "com.apple.pasteboard.promised-file-name",
        UTI.transient, UTI.autoGenerated,
        // References to state inside the source app: meaningless (or harmful) later.
        "com.apple.finder.noderef", "com.apple.photos.object-reference.asset", "PHObjectReferenceCookieType",
        "org.chromium.internal.source-rfh-token", "com.apple.is-remote-clipboard",
    ]

    /// Never read these: producing them has side effects in the source app
    /// (Word inserts bookmarks when asked for its link types).
    static func isUnsafeToRead(_ type: String) -> Bool {
        type == "com.microsoft.Link-Source" || type == "com.microsoft.ObjectLink" || type.hasPrefix("com.microsoft.ole.source")
    }

    /// Web archives can be tens of MB and duplicate the HTML next to them.
    static let webArchives: Set<String> = ["com.apple.webarchive", "Apple Web Archive pasteboard type"]

    /// Extra types that are redundant when an item already stands for a real file
    /// (we rewrite the file URL ourselves and can always re-derive icons).
    static let redundantForFiles: Set<String> = [UTI.fileURL, "com.apple.icns", "NSFilenamesPboardType",
                                                   "com.apple.finder.node", "public.url"]

    /// Reads everything, retrying once if the pasteboard changed while we were reading.
    public static func capture(_ pasteboard: NSPasteboard, limits: Limits = Limits()) -> CapturedClip {
        for _ in 0..<2 {
            let start = pasteboard.changeCount
            let clip = read(pasteboard, limits: limits)
            if pasteboard.changeCount == start { return clip }
        }
        return read(pasteboard, limits: limits)
    }

    private static func read(_ pasteboard: NSPasteboard, limits: Limits) -> CapturedClip {
        var elements: [CapturedClip.Element] = []
        var skipped: [String] = []
        var total = 0
        var concealed = false
        var source: String?

        for item in pasteboard.pasteboardItems ?? [] {
            let types = item.types.map(\.rawValue)
            if types.contains(UTI.concealed) { concealed = true }
            if types.contains(UTI.source), let value = item.string(forType: .init(UTI.source)) { source = value }

            var fileURL: URL?
            if types.contains(UTI.fileURL), let data = item.data(forType: .fileURL),
               let url = URL(dataRepresentation: data, relativeTo: nil), url.isFileURL {
                fileURL = url.standardizedFileURL
            }

            let hasHTML = types.contains(UTI.html)
            var entries: [CapturedClip.Entry] = []
            for type in types {
                if noise.contains(type) || type == UTI.concealed || type == UTI.source || isUnsafeToRead(type) { continue }
                if hasHTML && webArchives.contains(type) { skipped.append(type); continue }
                if fileURL != nil && (redundantForFiles.contains(type) || type.hasPrefix("dyn.")) { continue }
                guard let data = item.data(forType: .init(type)) else { continue }
                if data.count > limits.perType || total + data.count > limits.total {
                    skipped.append(type)
                    continue
                }
                total += data.count
                entries.append(.init(type: type, data: data))
            }
            if !entries.isEmpty || fileURL != nil {
                elements.append(.init(entries: entries, fileURL: fileURL))
            }
        }
        if !skipped.isEmpty { Log.capture.info("Skipped oversized types: \(skipped.joined(separator: ", "))") }
        return CapturedClip(elements: elements, concealed: concealed, sourceBundleID: source, skipped: skipped)
    }

    /// True when a drop carries file promises and no real files. Apple's samples prefer the
    /// promise: it's the original asset (Photos, Safari images, Preview page thumbnails, Mail),
    /// while any image data next to it is usually a lower-quality rendering.
    public static func needsFilePromises(_ pasteboard: NSPasteboard) -> Bool {
        let receivers = pasteboard.readObjects(forClasses: [NSFilePromiseReceiver.self], options: nil) ?? []
        guard !receivers.isEmpty else { return false }
        return !pasteboard.canReadObject(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true])
    }
}
#endif
